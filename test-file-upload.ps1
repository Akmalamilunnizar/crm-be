# Test file upload
Write-Host "Testing file upload API..."
Write-Host "API URL: $apiUrl"

try {
    $form = @{
        name = "test_document_$(Get-Date -Format 'yyyyMMdd_HHmmss')"
        path = "documents/test"
        file = Get-Item $testImagePath
    }
    
    $response = Invoke-RestMethod -Uri $apiUrl -Method Post -Form $form
    Write-Host "Upload successful!"
    Write-Host "Response:"
    $response | ConvertTo-Json -Depth 3
    
    if ($response.data.full_path) {
        Write-Host "File uploaded to: $($response.data.full_path)"
    } else {
        Write-Host "Warning: No full_path in response"
    }
    
} catch {
    Write-Host "Upload failed: $($_.Exception.Message)"
    if ($_.Exception.Response) {
        $reader = New-Object System.IO.StreamReader($_.Exception.Response.GetResponseStream())
        $responseBody = $reader.ReadToEnd()
        Write-Host "Response body: $responseBody"
    }
}

# Clean up test file
if (Test-Path $testImagePath) {
